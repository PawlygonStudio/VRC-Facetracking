using System.Collections.Generic;
using System.Linq;
using UnityEditor;
using UnityEditor.Animations;
using UnityEngine;
using VRC.SDK3.Avatars.Components;
using VRC.SDK3.Avatars.ScriptableObjects;

namespace Pawlygon.FaceTracking.Editor
{
    /// <summary>
    /// Reads the avatar's FX controller, expression parameters and menu, and creates the assets the components add.
    /// The avatar's own assets are only changed once VRCFury or Modular Avatar made build copies of them.
    /// </summary>
    internal static class FTAvatarAssets
    {
        public static RuntimeAnimatorController GetFX(VRCAvatarDescriptor descriptor)
        {
            if (!descriptor.customizeAnimationLayers || descriptor.baseAnimationLayers == null) return null;
            var layer = descriptor.baseAnimationLayers.FirstOrDefault(l => l.type == VRCAvatarDescriptor.AnimLayerType.FX);
            return layer.isDefault ? null : layer.animatorController;
        }

        /// <summary>
        /// The controllers that end up in FX before VRCFury and Modular Avatar run: the descriptor's own, and the ones
        /// their components will merge into FX. Legacy face tracking controllers are left out.
        /// </summary>
        public static List<(string source, AnimatorController controller)> GetSourceFXControllers(VRCAvatarDescriptor descriptor)
        {
            var result = new List<(string, AnimatorController)>();
            var seen = new HashSet<AnimatorController>();

            void Add(string source, RuntimeAnimatorController runtime)
            {
                if (FTAvatarUtils.BaseController(runtime) is AnimatorController controller && seen.Add(controller)) result.Add((source, controller));
            }

            var fx = GetFX(descriptor);
            if (fx != null) Add($"FX ({fx.name})", fx);

            var root = descriptor.transform;
            foreach (var behaviour in descriptor.GetComponentsInChildren<MonoBehaviour>(true))
            {
                if (behaviour == null || behaviour is VRC.SDKBase.VRC_AvatarDescriptor || behaviour is PawlygonFTComponent) continue;
                if (FTAvatarUtils.IsEditorOnly(behaviour.transform, root)) continue;

                foreach (var controller in FTAvatarUtils.GetReferencedControllers(behaviour, (int)VRCAvatarDescriptor.AnimLayerType.FX))
                {
                    if (LegacyOscDetector.IsPawlygonLegacyController(controller)) continue;
                    Add(FTAvatarUtils.GetPath(behaviour.transform, root), controller);
                }
            }
            return result;
        }

        /// <summary>The submenu control named <paramref name="name"/> in a menu, or null.</summary>
        public static VRCExpressionsMenu.Control FindSubmenu(VRCExpressionsMenu menu, string name)
        {
            return menu?.controls?.FirstOrDefault(c => c.type == VRCExpressionsMenu.Control.ControlType.SubMenu && c.name == name);
        }

        /// <summary>
        /// The avatar's FX controller, to edit in place. Only a controller VRCFury or Modular Avatar made for this
        /// build is edited, since copying the asset file would keep references into other files. Neither tool
        /// guarantees a full clone though: layers can still share state machines, states or clips with the
        /// originals, so existing layers are never edited, only replaced (see <see cref="FTFakePupilLayers.Empty"/>).
        /// </summary>
        public static AnimatorController GetBuildFX(VRCAvatarDescriptor descriptor)
        {
            var source = GetFX(descriptor);
            if (source is AnimatorController controller && IsBuildOwned(AssetDatabase.GetAssetPath(controller))) return controller;
            throw new FTBuildException($"The FX controller{(source != null ? $" '{source.name}'" : "")} wasn't made for this build by VRCFury or " +
                                       "Modular Avatar, so Pawlygon Face Tracking can't change it without changing the original.");
        }

        /// <summary>
        /// A controller that only exists for the current build: generated by VRCFury in its temp package, saved by
        /// NDMF / Modular Avatar in their generated folder, or not saved at all.
        /// </summary>
        static bool IsBuildOwned(string assetPath)
        {
            return string.IsNullOrEmpty(assetPath)
                   || assetPath.StartsWith("Packages/com.vrcfury.temp/")
                   || assetPath.StartsWith("Packages/nadena.dev.ndmf/__Generated/");
        }

        /// <summary>Adds a parameter unless one with that name exists. Returns false if it already existed.</summary>
        public static bool AddParameter(VRCExpressionParameters parameters, string name, VRCExpressionParameters.ValueType type,
            float defaultValue, bool saved, bool synced)
        {
            if (parameters.parameters.Any(p => p.name == name)) return false;
            parameters.parameters = parameters.parameters.Append(new VRCExpressionParameters.Parameter
            {
                name = name,
                valueType = type,
                defaultValue = defaultValue,
                saved = saved,
                networkSynced = synced,
            }).ToArray();
            EditorUtility.SetDirty(parameters);
            return true;
        }

        /// <summary>
        /// A menu control with every list filled in like the SDK's inspector does. Tools like Av3Emulator
        /// and Gesture Manager expect them and fail to draw the menu when they're null.
        /// </summary>
        public static VRCExpressionsMenu.Control CreateControl(string name, VRCExpressionsMenu.Control.ControlType type, string parameter, Texture2D icon)
        {
            return new VRCExpressionsMenu.Control
            {
                name = name,
                type = type,
                icon = icon,
                parameter = new VRCExpressionsMenu.Control.Parameter { name = parameter ?? "" },
                subParameters = new VRCExpressionsMenu.Control.Parameter[0],
                labels = new VRCExpressionsMenu.Control.Label[0],
                value = 1,
            };
        }

        public static VRCExpressionsMenu CreateMenu(string folder, string name)
        {
            var menu = ScriptableObject.CreateInstance<VRCExpressionsMenu>();
            menu.name = name;
            menu.controls = new List<VRCExpressionsMenu.Control>();
            AssetDatabase.CreateAsset(menu, AssetDatabase.GenerateUniqueAssetPath($"{folder}/{name}.asset"));
            return menu;
        }

        public static string SafeName(string name) => string.Concat(name.Select(c => char.IsLetterOrDigit(c) || c == ' ' || c == '-' ? c : '_'));
    }
}
